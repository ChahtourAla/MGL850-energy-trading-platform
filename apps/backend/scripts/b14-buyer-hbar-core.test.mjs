import test from 'node:test';
import assert from 'node:assert/strict';
import {parseTopUpHbar, parseBuyerTopupArgs,prepareBuyerTopup,existingTopupDisposition,checkStagingPermission,TINYBAR_TO_WEI} from './b14-buyer-hbar-core.mjs';
const id='60bd8ca9-bb7d-534f-8564-468e4a5f0b3a';
const buyer='0x255d93780b72aeb3c29187765d900eae4cf67f31';
const operator='0xD74a6786587A2a936cFb059fec998Ad6DB300F37';
const ext='0xcf7dd5496d70fc9010f07f177c85869f52fb3d3d8200220a628bc1a10e931f07';
const positive={matchId:id,buyerAddress:buyer,operatorAddress:operator,externalTradeId:ext,
 topupWei:parseTopUpHbar('0.2').valueWei,buyerBalanceWei:'0',operatorBalanceWei:'1000000000000000000000',
 operatorHasRole:true,networkChainId:296, existingLocalTrade:null, existingOnChainId:'0',matchStatus:'SELECTED',maxExistingBuyerWei:'50000000000000000'};
const cli=['--match-id',id,'--operator-address',operator,'--hbar','0.2'];
const p=()=>prepareBuyerTopup(positive);
test('parse exact 0.2 HBAR as 20m tinybar',()=>assert.equal(parseTopUpHbar('0.2').tinybar,20_000_000n));
test('convert tinybar into EVM wei exactly',()=>assert.equal(parseTopUpHbar('0.2').valueWei,'200000000000000000'));
test('0.1 HBAR lower bound',()=>assert.equal(parseTopUpHbar('0.1').tinybar,10_000_000n));
test('1 HBAR upper bound',()=>assert.equal(parseTopUpHbar('1').tinybar,100_000_000n));
test('reject zero',()=>assert.throws(()=>parseTopUpHbar('0')));
test('reject below minimum',()=>assert.throws(()=>parseTopUpHbar('0.09')));
test('reject above maximum',()=>assert.throws(()=>parseTopUpHbar('1.1')));
test('reject scientific notation',()=>assert.throws(()=>parseTopUpHbar('2e-1')));
test('reject >8 decimals',()=>assert.throws(()=>parseTopUpHbar('0.123456789')));
test('reject signing prefix',()=>assert.throws(()=>parseTopUpHbar('+0.2')));
test('CLI defaults read-only',()=>assert.equal(parseBuyerTopupArgs(cli).stage,false));
test('CLI requires all params',()=>assert.throws(()=>parseBuyerTopupArgs(cli.slice(0,4))));
test('CLI rejects repeated flag',()=>assert.throws(()=>parseBuyerTopupArgs([...cli,'--hbar','0.3'])));
test('CLI rejects unknown flags',()=>assert.throws(()=>parseBuyerTopupArgs([...cli,'--execute'])));
test('CLI accepts explicitly staged request',()=>assert.equal(parseBuyerTopupArgs([...cli,'--stage']).stage,true));
test('DB stage needs confirmation gate',()=>assert.throws(()=>checkStagingPermission({stage:true},{})));
test('DB stage with explicit gate allowed',()=>assert.equal(checkStagingPermission({stage:true},{B14_STAGE_INTENT_CONFIRM:'YES'}),true));
test('preview never stages',()=>assert.equal(checkStagingPermission({stage:false},{B14_STAGE_INTENT_CONFIRM:'YES'}),false));
test('canonical operation is FUND_BUYER_HBAR',()=>assert.equal(p().operation,'FUND_BUYER_HBAR'));
test('canonical transfer uses no calldata',()=>assert.equal(p().callData,'0x'));
test('canonical transfer uses operator as signer',()=>assert.equal(p().signerAddress,operator.toLowerCase()));
test('canonical transfer directs to B07 buyer',()=>assert.equal(p().targetAddress,buyer.toLowerCase()));
test('canonical request digest is deterministic',()=>assert.equal(p().payloadSha256,p().payloadSha256));
test('new journal requires create',()=>assert.equal(existingTopupDisposition(null,p()),'CREATE'));
test('identical planned journal is unchanged',()=>assert.equal(existingTopupDisposition({...p(),status:'PLANNED'},p()),'UNCHANGED'));
test('no replanning after SIGNED',()=>assert.throws(()=>existingTopupDisposition({...p(),status:'SIGNED'},p())));
test('changed transfer cannot reuse row',()=>assert.throws(()=>existingTopupDisposition({...p(),status:'PLANNED'},prepareBuyerTopup({...positive,topupWei:parseTopUpHbar('0.3').valueWei}))));
test('reject wrong network',()=>assert.throws(()=>prepareBuyerTopup({...positive,networkChainId:295})));
test('reject operator without role',()=>assert.throws(()=>prepareBuyerTopup({...positive,operatorHasRole:false})));
test('reject already created trade',()=>assert.throws(()=>prepareBuyerTopup({...positive,existingOnChainId:'2'})));
test('reject existing local trade',()=>assert.throws(()=>prepareBuyerTopup({...positive,existingLocalTrade:{id:'abc'}})));
test('reject nonselected match',()=>assert.throws(()=>prepareBuyerTopup({...positive,matchStatus:'TRADE_CREATED'})));
test('reject self funding',()=>assert.throws(()=>prepareBuyerTopup({...positive,buyerAddress:operator})));
test('reject wallet already above threshold',()=>assert.throws(()=>prepareBuyerTopup({...positive,buyerBalanceWei:'50000000000000000'})));
test('reject insufficient operator balance',()=>assert.throws(()=>prepareBuyerTopup({...positive,operatorBalanceWei:parseTopUpHbar('0.2').valueWei})));
test('reject wei that cannot be expressed as tinybar',()=>assert.throws(()=>prepareBuyerTopup({...positive,topupWei:'200000000000000001'})));
test('positive plan only within the fixed ceiling',()=>assert.ok(BigInt(p().valueWei) <= 100_000_000n * TINYBAR_TO_WEI));
